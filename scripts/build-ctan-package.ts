/**
 * Builds the CTAN package `katibmath` from the app's symbol registry.
 *
 *   npx vite-node scripts/build-ctan-package.ts
 *
 * Writes ctan/katibmath/: katibmath.sty, katibmath-symbols.tex (the symbol
 * table included by the manual), plus the font and its licence copied from
 * fonts-src/katib-math/dist. The manual (katibmath.tex) and README.md are
 * hand-written; compile the manual with XeLaTeX to get katibmath.pdf.
 *
 * The package and the app's LaTeX export use the same symbol bodies
 * (src/lib/math/to-latex.ts), so every command means the same in both.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ensureBuiltinSymbols } from '../src/lib/math/index';
import { getSymbols, getSymbolSource, type MathSymbol } from '../src/lib/math/registry';
import { collectUsedSymbols } from '../src/lib/math/tex-macros';
import { latexBodyOf } from '../src/lib/math/to-latex';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'ctan', 'katibmath');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as { version: string };

const VERSION = process.env.KATIBMATH_VERSION ?? '0.1.0';
const DATE = new Date().toISOString().slice(0, 10).replace(/-/g, '/');

ensureBuiltinSymbols();
const builtins = getSymbols().filter((s) => getSymbolSource(s.name) === 'builtin');

/** The package's own helper names instead of the exporter's \sw… helpers. */
function packageBody(sym: MathSymbol): string {
  return latexBodyOf(sym).replaceAll('\\swmirror', '\\katibmirror').replaceAll('\\swmathglyphs', '\\katibglyphs');
}

const ordered = collectUsedSymbols(
  builtins.map((s) => `\\${s.name}`),
  builtins,
  packageBody,
);

const CATEGORY_TITLES: Record<string, { en: string; ar: string }> = {
  'arabic-function': { en: 'Functions and limits', ar: 'الدوال والنهايات' },
  'arabic-letter': { en: 'Arabic mathematical alphabet', ar: 'الأبجدية الرياضية العربية' },
  operator: { en: 'Mirrored operators', ar: 'المؤثرات المعكوسة' },
  relation: { en: 'Relations and notation', ar: 'العلاقات والترميز' },
  arrow: { en: 'Arrows', ar: 'الأسهم' },
  unit: { en: 'Units', ar: 'الوحدات' },
  misc: { en: 'Signs and number sets', ar: 'إشارات ومجموعات أعداد' },
};

function definitions(): string {
  return ordered
    .map((s) => {
      const arity = s.arity && s.arity > 0 ? `[${s.arity}]` : '';
      return `\\DeclareRobustCommand{\\${s.name}}${arity}{${packageBody(s)}}`;
    })
    .join('\n');
}

const sty = String.raw`%% katibmath.sty — Arabic mathematical notation for XeLaTeX and LuaLaTeX
%% Generated by scripts/build-ctan-package.ts from the symbol registry of
%% الكاتب العلمي (Scientific Writer). Do not edit by hand.
%%
%% Copyright (C) ${new Date().getFullYear()} Muhammad Nabeel Shaesha
%%
%% This work may be distributed and/or modified under the conditions of the
%% LaTeX Project Public License, either version 1.3c of this license or (at
%% your option) any later version. The latest version of this license is in
%%   https://www.latex-project.org/lppl.txt
%% This work has the LPPL maintenance status "maintained".
%% The font KatibMath-Regular.otf is under the SIL Open Font License 1.1.
\NeedsTeXFormat{LaTeX2e}[2020/10/01]
\ProvidesPackage{katibmath}[${DATE} v${VERSION} Arabic mathematical notation]

\RequirePackage{iftex}
\RequireTUTeX

%% Options
%%   mathfont   (default) use Katib Math as the math font (\setmathfont)
%%   nomathfont keep the document's math font; Arabic symbols still use Katib Math
\newif\ifkatib@mathfont \katib@mathfonttrue
\DeclareOption{mathfont}{\katib@mathfonttrue}
\DeclareOption{nomathfont}{\katib@mathfontfalse}
\ProcessOptions\relax

\RequirePackage{amsmath}
\RequirePackage{graphicx}
\RequirePackage{fontspec}
\RequirePackage{unicode-math}

\ifkatib@mathfont
  \setmathfont{KatibMath-Regular.otf}
\fi

%% \katibglyphs: Katib Math as a text font, for the Arabic Mathematical
%% Alphabetic Symbols (U+1EE00–1EEFF) and the Arabic math signs, which
%% unicode-math does not map into math mode.
\newfontfamily\katibglyphs{KatibMath-Regular.otf}

%% \katibarabic: Katib Math's Arabic (from Amiri), shaped, for Arabic words
%% in formulas (جا، نها، لـو …).
\newfontfamily\katibarabic{KatibMath-Regular.otf}[Script=Arabic,BoldFeatures={FakeBold=2.5}]

%% \katibmirror{x}: x flipped horizontally, keeping the current math style,
%% so mirrored big operators stay large and keep their limits.
\newcommand{\katibmirror}[1]{\mathpalette\katib@mirror{#1}}
\newcommand{\katib@mirror}[2]{\reflectbox{$\m@th#1#2$}}

%% Arabic text inside math. polyglossia and babel define \textarabic; without
%% them, katibmath supplies one that sets the text right to left in Katib Math.
%% It also works in math mode (it switches to text with amsmath's \text).
\newcommand{\katib@textarabic}[1]{%
  \ifLuaTeX
    {\katibarabic\textdir TRT #1}%
  \else
    {\TeXXeTstate=1 \katibarabic\beginR #1\endR}%
  \fi}
\AtBeginDocument{%
  \providecommand{\textarabic}[1]{%
    \ifmmode\text{\katib@textarabic{#1}}\else\katib@textarabic{#1}\fi}%
}

%% ── Symbols (${ordered.length}) ──
${definitions()}

\endinput
`;

/** A sample call for the manual's table. */
function sample(s: MathSymbol): string {
  if (s.arity === 1) return `\\${s.name}{x}`;
  if (s.arity === 2) return `\\${s.name}{3}{x}`;
  return `\\${s.name}`;
}

function texEscape(s: string): string {
  return s.replace(/[\\{}$&#%_^~]/g, (c) => `\\${c === '\\' ? 'textbackslash' : c}{}`.replace('\\{{}', '\\{').replace('\\}{}', '\\}'));
}

function symbolTable(): string {
  const parts: string[] = [];
  const cats = [...new Set(builtins.map((s) => s.category))];
  for (const cat of cats) {
    const title = CATEGORY_TITLES[cat] ?? { en: cat, ar: cat };
    parts.push(`\\subsection*{${title.en} \\quad \\textarabic{${title.ar}}}`);
    parts.push('\\begin{longtable}{@{}l c c r@{}}');
    parts.push('\\toprule Command & Symbol & Example & \\textarabic{الاسم} \\\\ \\midrule \\endhead');
    for (const s of builtins.filter((x) => x.category === cat)) {
      const call = sample(s);
      parts.push(
        `\\verb|${call}| & $${call}$ & $\\displaystyle ${call}$ & \\textarabic{${texEscape(s.labelAr)}} \\\\`,
      );
    }
    parts.push('\\bottomrule\n\\end{longtable}');
  }
  return parts.join('\n');
}

mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'katibmath.sty'), sty.replace(/\r?\n/g, '\n'));
writeFileSync(
  join(out, 'katibmath-symbols.tex'),
  `% Generated by scripts/build-ctan-package.ts. Do not edit by hand.\n${symbolTable()}\n`,
);
const fontDir = join(root, 'fonts-src', 'katib-math', 'dist');
copyFileSync(join(fontDir, 'KatibMath-Regular.otf'), join(out, 'KatibMath-Regular.otf'));
copyFileSync(join(fontDir, 'OFL.txt'), join(out, 'OFL.txt'));
console.log(`katibmath v${VERSION} (app ${pkg.version}): ${ordered.length} symbols → ${out}`);
