"""
Generate src/lib/math/symbols/arabic-alphabet.ts — one glyph symbol per
assigned character of the Arabic Mathematical Alphabetic Symbols block
(U+1EE00–U+1EEFF), from Python's own Unicode database (no download).

    python scripts/gen-arabic-alphabet.py

Macro names: "ar" + variant + letter, letters only (registry rule), e.g.
\\arBeh, \\arInitJeem, \\arTailNoon, \\arStretchSeen, \\arLoopAin,
\\arDsDal (double-struck), \\arDotlessBeh, \\arOpMeemHah (operators).
"""
from __future__ import annotations

import json
import sys
import unicodedata as ud
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "lib" / "math" / "symbols" / "arabic-alphabet.ts"

# Unicode variant word -> (macro infix, Arabic label suffix, English keyword)
VARIANTS = {
    "": ("", "", "isolated"),
    "DOTLESS": ("Dotless", "بلا نقط", "dotless"),
    "INITIAL": ("Init", "مستهلّة", "initial"),
    "TAILED": ("Tail", "بذيل", "tailed"),
    "STRETCHED": ("Stretch", "ممدودة", "stretched"),
    "LOOPED": ("Loop", "معقودة", "looped"),
    "DOUBLE-STRUCK": ("Ds", "مزدوجة", "double-struck"),
}

OPERATORS = {
    # U+1EEF0, U+1EEF1: Arabic summation-like and limit-like operators
    "MEEM WITH HAH WITH TATWEEL": ("OpMeemHah", "مؤثر مح (مجموع)", ["sum", "مجموع", "مح"]),
    "HAH WITH DAL": ("OpHahDal", "مؤثر حد (نهاية)", ["limit", "نهاية", "حد"]),
}


def camel(words: str) -> str:
    return "".join(w.capitalize() for w in words.replace("-", " ").split())


def arabic_letter(base: str, variant: str) -> str:
    """The ordinary Arabic letter for a label, e.g. 'BEH' -> 'ب'."""
    for name in ([f"ARABIC LETTER DOTLESS {base}"] if variant == "DOTLESS" else []) + [f"ARABIC LETTER {base}"]:
        try:
            return ud.lookup(name)
        except KeyError:
            continue
    return ""


def main() -> int:
    entries = []
    for cp in range(0x1EE00, 0x1EF00):
        name = ud.name(chr(cp), "")
        if not name:
            continue
        rest = name.removeprefix("ARABIC MATHEMATICAL ")
        if rest.startswith("OPERATOR "):
            key = rest.removeprefix("OPERATOR ")
            infix, label, keywords = OPERATORS[key]
            entries.append({
                "name": "ar" + infix, "cp": cp, "labelAr": label,
                "keywords": keywords + ["operator", "مؤثر"], "atom": "mathop",
            })
            continue
        variant = next((v for v in VARIANTS if v and rest.startswith(v + " ")), "")
        base = rest.removeprefix(variant + " ") if variant else rest
        infix, suffix, kw = VARIANTS[variant]
        letter = arabic_letter(base, variant)
        entries.append({
            "name": "ar" + infix + camel(base),
            "cp": cp,
            "labelAr": f"{letter} {suffix}".strip() if letter else f"{camel(base)} {suffix}".strip(),
            "keywords": [k for k in (letter, base.lower(), kw, "arabic letter", "حرف") if k],
            "atom": "mathord",
        })

    names = [e["name"] for e in entries]
    if len(set(names)) != len(names):
        dupes = sorted({n for n in names if names.count(n) > 1})
        print("duplicate macro names:", dupes, file=sys.stderr)
        return 1

    lines = [
        "/**",
        " * GENERATED by scripts/gen-arabic-alphabet.py — do not edit by hand.",
        " *",
        " * Arabic Mathematical Alphabetic Symbols (U+1EE00–U+1EEFF) as glyph",
        f" * symbols drawn with Katib Math (class sw-font-arabicmath). {len(entries)} symbols,",
        f" * Unicode {ud.unidata_version}.",
        " */",
        "import type { MathSymbol, GlyphAtom } from '../registry';",
        "",
        "export type ArabicLetterVariant = 'isolated' | 'dotless' | 'initial' | 'tailed' | 'stretched' | 'looped' | 'double-struck' | 'operator';",
        "",
        "function glyph(name: string, cp: number, labelAr: string, keywords: string[], atom: GlyphAtom): MathSymbol {",
        "  const char = String.fromCodePoint(cp);",
        "  return {",
        "    name,",
        "    category: 'arabic-letter',",
        "    labelAr,",
        "    keywords,",
        "    unicode: char,",
        "    katex: { kind: 'glyph', char, font: 'arabicmath', atom },",
        "    latex: { body: char },",
        "    typst: char,",
        "  };",
        "}",
        "",
        "/** Variant of an Arabic math letter, from its macro name. */",
        "export function arabicLetterVariant(name: string): ArabicLetterVariant {",
        "  if (name.startsWith('arOp')) return 'operator';",
        "  if (name.startsWith('arDotless')) return 'dotless';",
        "  if (name.startsWith('arInit')) return 'initial';",
        "  if (name.startsWith('arTail')) return 'tailed';",
        "  if (name.startsWith('arStretch')) return 'stretched';",
        "  if (name.startsWith('arLoop')) return 'looped';",
        "  if (name.startsWith('arDs')) return 'double-struck';",
        "  return 'isolated';",
        "}",
        "",
        "export const ARABIC_ALPHABET: MathSymbol[] = [",
    ]
    for e in entries:
        lines.append(
            f"  glyph({json.dumps(e['name'])}, 0x{e['cp']:X}, {json.dumps(e['labelAr'], ensure_ascii=False)}, "
            f"{json.dumps(e['keywords'], ensure_ascii=False)}, '{e['atom']}'),"
        )
    lines += ["];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(entries)} symbols)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
