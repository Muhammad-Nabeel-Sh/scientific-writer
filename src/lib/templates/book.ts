import type { Template } from './types';
import type { TreeNode } from '$lib/stores';
import { createId } from '$lib/utils';
import { introContent, conclusionContent, referencesContent } from './content';

function node(name: string, type: 'note' | 'folder', children?: TreeNode[]): TreeNode {
  return { id: createId(), name, type, children, expanded: true };
}

export const bookTemplate: Template = {
  id: 'book',
  name: 'كتاب',
  description: 'هيكل كتاب علمي متكامل يشمل أبواباً وفصولاً مع مقدمات وملاحق وخاتمة',
  generate() {
    const tree: TreeNode[] = [];
    const samples: Record<string, string> = {};

    const introN = node('المقدمة', 'note');
    tree.push(introN);

    const part1 = node('الباب الأول: الأسس النظرية', 'folder', [
      node('الفصل الأول: مفاهيم تمهيدية', 'note'),
      node('الفصل الثاني: الإطار النظري', 'note'),
    ]);
    tree.push(part1);

    const part2 = node('الباب الثاني: التطبيقات العملية', 'folder', [
      node('الفصل الثالث: تحليل ومناقشة', 'note'),
      node('الفصل الرابع: تطبيقات وحالات دراسية', 'note'),
    ]);
    tree.push(part2);

    const concN = node('الخاتمة', 'note');
    tree.push(concN);

    const appendices = node('الملاحق', 'folder', [
      node('ملحق أ: أدوات الدراسة', 'note'),
      node('ملحق ب: جداول إحصائية', 'note'),
    ]);
    tree.push(appendices);

    const refN = node('المراجع', 'note');
    tree.push(refN);

    samples[introN.id] = introContent();
    samples[part1.children![0].id] = `# الفصل الأول: مفاهيم تمهيدية

## تعريف المفاهيم الأساسية

يهدف هذا الفصل إلى تقديم المفاهيم الأساسية التي سيعتمد عليها الكتاب، وذلك لضمان فهم موحد للمصطلحات المستخدمة.

### المفهوم الأول: التعريف والخصائص

يمكن تعريف المفهوم الأول بأنه "مجموعة الخصائص والسمات التي تميز ظاهرة معينة عن غيرها".

#### الخصائص الرئيسية:

1. **الشمولية**: يغطي المفهوم جميع جوانب الظاهرة
2. **التجريد**: يمثل المفهوم فكرة مجردة قابلة للتطبيق
3. **القابلية للقياس**: يمكن ترجمة المفهوم إلى مؤشرات قابلة للقياس

### المفهوم الثاني: الأهمية والتطبيقات

يرتبط هذا المفهوم بالجوانب التطبيقية للدراسة.

## تصنيف المفاهيم

يمكن تصنيف المفاهيم وفقاً لعدة معايير:

$$
\\begin{matrix}
\\text{مفاهيم نظرية} & \\longrightarrow & \\text{قابلة للتجريد} \\\\
\\text{مفاهيم تطبيقية} & \\longrightarrow & \\text{قابلة للقياس}
\\end{matrix}
$$`;
    samples[part1.children![1].id] = `# الفصل الثاني: الإطار النظري

## النظريات المفسرة

### النظرية الأولى

تقوم هذه النظرية على افتراض أن الظاهرة المدروسة تتأثر بمجموعة من العوامل الأساسية.

### النظرية الثانية

تركز هذه النظرية على العلاقات التفاعلية بين المتغيرات.

### النظرية الثالثة

تدمج هذه النظرية بين المقاربات السابقة في إطار متكامل.

## النماذج التطبيقية

| النموذج | الأسس | التطبيقات |
|---------|-------|-----------|
| النموذج (أ) | نظري | تحليلي |
| النموذج (ب) | تطبيقي | ميداني |
| النموذج (ج) | مختلط | شامل |

## خلاصة الفصل

يخلص هذا الفصل إلى أن الإطار النظري المتكامل يتطلب الجمع بين المقاربات المختلفة لتحقيق فهم شامل للظاهرة المدروسة.`;
    samples[part2.children![0].id] = `# الفصل الثالث: تحليل ومناقشة

## منهجية التحليل

تم في هذا الفصل تحليل الظاهرة وفقاً للإطار النظري الذي تم بناؤه في الأبواب السابقة.

### خطوات التحليل

1. جمع البيانات من المصادر المختلفة
2. تصنيف البيانات حسب الموضوعات
3. تحليل البيانات باستخدام الأدوات المناسبة
4. استخلاص النتائج

## نتائج التحليل

### المحور الأول: التحليل النظري

أظهر التحليل النظري أن الظاهرة تتسم بالتعددية والتعقيد.

### المحور الثاني: التحليل التطبيقي

تطابق التحليل التطبيقي مع الإطار النظري في معظم الجوانب.

$$
R^2 = 1 - \\frac{SS_{res}}{SS_{tot}}
$$`;
    samples[part2.children![1].id] = `# الفصل الرابع: تطبيقات وحالات دراسية

## الحالة الدراسية الأولى

### وصف الحالة

تتعلق هذه الحالة بتطبيق الإطار النظري في سياق عملي محدد.

### التحليل

تم تطبيق أدوات التحليل على بيانات الحالة، وأظهرت النتائج مطابقة للنموذج النظري.

### الدروس المستفادة

- أهمية التطبيق العملي للنظريات
- ضرورة تكييف الإطار النظري مع السياق
- الحاجة إلى أدوات تقييم مناسبة

## الحالة الدراسية الثانية

### وصف الحالة

حالة مختلفة في السياق ولكنها تطبق نفس الإطار النظري.`;
    samples[concN.id] = conclusionContent();
    samples[appendices.children![0].id] = `# ملحق أ: أدوات الدراسة

## استمارة المقابلة

### الأسئلة الرئيسية

1. ما تقييمك للإطار النظري المقترح؟
2. هل تجد أن النموذج المطبق يحقق الأهداف المرجوة؟
3. ما التحديات التي تواجه تطبيق هذا النموذج؟

## استبانة القياس

| الرقم | العبارة | موافق بشدة | موافق | محايد | غير موافق | غير موافق بشدة |
|-------|---------|-----------|-------|-------|-----------|---------------|
| 1 | العبارة الأولى | | | | | |
| 2 | العبارة الثانية | | | | | |
| 3 | العبارة الثالثة | | | | | |`;
    samples[appendices.children![1].id] = `# ملحق ب: جداول إحصائية

## جدول توزيع المجتمع

| الفئة | العدد | النسبة المئوية |
|-------|-------|----------------|
| الفئة الأولى | 150 | 30% |
| الفئة الثانية | 200 | 40% |
| الفئة الثالثة | 150 | 30% |
| **المجموع** | **500** | **100%** |

## نتائج الاختبارات الإحصائية

$$
\\begin{array}{|l|c|c|}
\\hline
\\text{الاختبار} & \\text{القيمة} & \\text{الدلالة} \\\\
\\hline
\\text{بيرسون} & 0.72 & p < 0.01 \\\\
\\text{ت} & 3.45 & p < 0.001 \\\\
\\text{ف} & 5.67 & p < 0.05 \\\\
\\hline
\\end{array}
$$`;
    samples[refN.id] = referencesContent();

    return { tree, samples };
  },
};
