import { describe, expect, it } from 'vitest';
import {
  LatexExporter,
  escapeLatex,
  latexLabel,
  numeralsFor,
} from '$lib/publishing/latex-exporter';
import type { DocumentMeta, DocumentModel } from '$lib/publishing/ast';

function model(meta: Partial<DocumentMeta>, blocks: DocumentModel['blocks'] = []): DocumentModel {
  return { meta, blocks, bibEntries: [], errors: [] };
}

function exportTex(m: DocumentModel): string {
  return new LatexExporter().export(m).content as string;
}

describe('escapeLatex', () => {
  it('uses text commands for backslash, tilde and caret', () => {
    expect(escapeLatex('\\')).toBe('\\textbackslash{}');
    expect(escapeLatex('~')).toBe('\\textasciitilde{}');
    expect(escapeLatex('^')).toBe('\\textasciicircum{}');
  });

  it('escapes the remaining specials', () => {
    expect(escapeLatex('{}&%$#_')).toBe('\\{\\}\\&\\%\\$\\#\\_');
  });

  it('does not re-escape braces generated by the backslash replacement', () => {
    expect(escapeLatex('a\\b{c}')).toBe('a\\textbackslash{}b\\{c\\}');
  });
});

describe('LaTeX labels', () => {
  it('keeps Unicode letters and replaces unsafe characters', () => {
    expect(latexLabel('energy')).toBe('energy');
    expect(latexLabel('سرعة')).toBe('سرعة');
    expect(latexLabel('a b/c')).toBe('a-b-c');
    expect(latexLabel('  ')).toBe('eq');
  });
});

describe('numerals', () => {
  it('maps the app digit style to polyglossia options', () => {
    expect(numeralsFor('western', true)).toBe('maghrib');
    expect(numeralsFor('eastern', true)).toBe('mashriq');
    expect(numeralsFor('auto', true)).toBe('mashriq');
    expect(numeralsFor('auto', false)).toBe('maghrib');
    expect(numeralsFor(undefined, true)).toBe('mashriq');
  });
});

describe('LaTeX preamble', () => {
  it('adds amsmath/mathtools and unicode-math with Katib Math for RTL', () => {
    const tex = exportTex(model({
      lang: 'ar',
      direction: 'rtl',
      digitStyle: 'eastern',
      arabicFont: 'Amiri',
    }));
    for (const needle of [
      '\\usepackage{amsmath,amssymb,mathtools}',
      '\\usepackage{unicode-math}',
      '\\setmathfont[Path=./]{KatibMath-Regular.otf}',
      '\\setmainfont{Amiri}',
      '\\newfontfamily\\arabicfont[Script=Arabic,Scale=1.2]{Amiri}',
      '\\setmainlanguage[numerals=mashriq]{arabic}',
      '% Compile with: xelatex',
    ]) {
      expect(tex).toContain(needle);
    }
  });

  it('uses maghrib for western digits and defaults the Arabic font to Amiri', () => {
    const tex = exportTex(model({ lang: 'ar', direction: 'rtl', digitStyle: 'western' }));
    expect(tex).toContain('\\setmainlanguage[numerals=maghrib]{arabic}');
    expect(tex).toContain('\\setmainfont{Amiri}');
  });

  it('keeps the LTR preamble free of XeLaTeX-only packages', () => {
    const tex = exportTex(model({ lang: 'en', direction: 'ltr', digitStyle: 'western' }));
    expect(tex).toContain('\\usepackage{amsmath,amssymb,mathtools}');
    expect(tex).toContain('\\usepackage[utf8]{inputenc}');
    expect(tex).not.toContain('\\setmathfont');
  });
});

describe('LaTeX equations', () => {
  it('emits labels and eqrefs', () => {
    const tex = exportTex(model({}, [
      { type: 'paragraph', children: [{ type: 'equationRef', ref: 'energy' }] },
      { type: 'mathBlock', value: 'E=mc^2', label: 'energy', number: 1 },
    ]));
    expect(tex).toContain('\\eqref{eq:energy}');
    expect(tex).toContain('\\label{eq:energy}');
  });

  it('uses the equation number as a label when there is no explicit label', () => {
    const tex = exportTex(model({}, [
      { type: 'paragraph', children: [{ type: 'equationRef', ref: '2' }] },
      { type: 'mathBlock', value: 'x^2', number: 2 },
    ]));
    expect(tex).toContain('\\eqref{eq:2}');
    expect(tex).toContain('\\label{eq:2}');
  });
});
